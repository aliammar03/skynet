def _remove_tree(path: Path) -> None:
    try:
        shutil.rmtree(path)
    except FileNotFoundError:
        pass
    except OSError:
        pass


def _publish(output: Path, pages: Mapping[Path, str], host_names: set[str]) -> None:
    output.parent.mkdir(parents=True, exist_ok=True)
    staging = Path(tempfile.mkdtemp(prefix=".skynet-render-", dir=output.parent))
    temporary: Path | None = staging
    backup: Path | None = None
    published = False
    try:
        if output.is_dir():
            shutil.copytree(output, staging, dirs_exist_ok=True)
        for relative, content in pages.items():
            staged = staging / relative
            staged.parent.mkdir(parents=True, exist_ok=True)
            staged.write_text(content, encoding="utf-8")
        hosts = staging / "40-hosts"
        if hosts.is_dir():
            for path in hosts.glob("*.md"):
                if path.name not in host_names:
                    path.unlink()
        if output.exists():
            backup = Path(tempfile.mkdtemp(prefix=".skynet-render-backup-", dir=output.parent))
            backup.rmdir()
            os.replace(output, backup)
        try:
            os.replace(staging, output)
            temporary = None
            published = True
        except OSError:
            if backup is not None:
                try:
                    os.replace(backup, output)
                    backup = None
                except OSError:
                    raise RenderError(
                        f"generated-page publication and rollback failed; prior pages remain at {backup}",
                        3,
                    ) from None
            raise
    except OSError:
        raise RenderError("generated-page publication failed", 3) from None
    finally:
        if temporary is not None:
            _remove_tree(temporary)
        if backup is not None and published:
            _remove_tree(backup)


def render_docs(
    repo: Path, output: Path | None = None, *, timestamp: str | None = None
) -> RenderResult:
    """Build all factual pages, then publish them without exposing failed partial output."""
    repo = repo.resolve()
    inventory = repo / "inventory"
    target = (output or repo / "docs/generated").resolve()
    if not inventory.is_dir():
        raise RenderError("inventory source directory unavailable", 3)
    if not any(path.is_file() and path.stat().st_size for path in inventory.rglob("*.json")):
        raise RenderError("no inventory JSON yet — collectors have not run", 3)
    lab_path = repo / "lab.json"
    lab = _object(_json_optional(lab_path), lab_path)
    vlans = lab.get("vlans", {})
    if not isinstance(vlans, dict):
        raise RenderError(f"{lab_path}: malformed VLAN declarations")
    vlan_names = {
        int(row["vlan"]): _text(row.get("name"))
        for row in _objects(vlans.get("list"), lab_path, "vlans.list")
        if "vlan" in row
    }
    hosts, vhosts = _cache_rows(repo)
    hosts.sort(key=_ip_key)
    moment = timestamp or datetime.now().astimezone().isoformat(timespec="seconds")
    firewall_path = inventory / "firewall/firewall.json"
    firewall = _json_optional(firewall_path)
    pages: dict[Path, str] = {
        Path("00-network-map.md"): _page_network(hosts, vlan_names, moment),
        Path("10-vlans.md"): _page_vlans(hosts, vlan_names, moment),
        Path("20-firewall.md"): _page_firewall(inventory, firewall, moment),
        Path("30-services/README.md"): _page_services(inventory, vhosts, moment),
        Path("90-backup-status.md"): _page_backup(inventory, moment),
        Path("50-network-gear.md"): _page_network_gear(inventory, firewall, moment),
    }
    nodes: list[str] = []
    for label, name in (("core", "proxmox-core.json"), ("network", "proxmox-network.json")):
        path = inventory / name
        value = _json_optional(path)
        if value is None:
            continue
        node, content = _node_page(path, value, label, moment)
        nodes.append(node)
        pages[Path("40-hosts") / f"{node}.md"] = content
    pages[Path("README.md")] = _index(nodes, moment)
    host_names = {path.name for path in pages if path.parent == Path("40-hosts")}
    _publish(target, pages, host_names)
    return RenderResult(target, tuple(sorted(pages)))
